-- =============================================================
-- F10 공지사항: 조회수
--   공지 상세를 조회할 때마다 view_count 를 +1 한다(기본 CRUD + 조회수).
--   notices 테이블 자체는 V1 에 이미 있고(제목/본문/고정), 조회수 컬럼만 추가한다.
-- =============================================================
ALTER TABLE notices
    ADD COLUMN view_count INT NOT NULL DEFAULT 0
    COMMENT '공지 상세 조회수(상세 조회 시 +1)';
